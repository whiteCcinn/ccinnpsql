-- Features of PostgreSQL 10+ (declarative partitioning), 11+ (procedures) and 12+ (generated columns).
-- Run after seed-demo.sql on servers that support them; each block checks the version.
SET search_path TO shop, public;
DO $do$
BEGIN
    IF current_setting('server_version_num')::int >= 100000 THEN
        EXECUTE $sql$
            CREATE TABLE measurements (
                id bigint GENERATED BY DEFAULT AS IDENTITY,
                sensor text NOT NULL,
                recorded_at date NOT NULL,
                value double precision
            ) PARTITION BY RANGE (recorded_at)$sql$;
        EXECUTE $sql$CREATE TABLE measurements_2025 PARTITION OF measurements FOR VALUES FROM ('2025-01-01') TO ('2026-01-01')$sql$;
        EXECUTE $sql$CREATE TABLE measurements_2026 PARTITION OF measurements FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')$sql$;
        EXECUTE $sql$CREATE TABLE measurements_2027 PARTITION OF measurements FOR VALUES FROM ('2027-01-01') TO ('2028-01-01')$sql$;
        EXECUTE $sql$INSERT INTO measurements (sensor, recorded_at, value)
                     SELECT 'sensor-' || (g % 7), date '2025-01-01' + (g % 900), random() * 100 FROM generate_series(1, 3000) g$sql$;
    END IF;
    IF current_setting('server_version_num')::int >= 110000 THEN
        EXECUTE $sql$CREATE PROCEDURE archive_events(p_before timestamptz) LANGUAGE plpgsql AS $body$
            BEGIN
                INSERT INTO shop.events_archive (payload, archived_by) SELECT payload, 'archive_events' FROM ONLY shop.events WHERE happened_at < p_before;
                DELETE FROM ONLY shop.events WHERE happened_at < p_before;
            END $body$$sql$;
    END IF;
    IF current_setting('server_version_num')::int >= 120000 THEN
        EXECUTE $sql$ALTER TABLE products ADD COLUMN price_with_tax numeric(10,2) GENERATED ALWAYS AS (price * 1.06) STORED$sql$;
    END IF;
END $do$;
ANALYZE;
