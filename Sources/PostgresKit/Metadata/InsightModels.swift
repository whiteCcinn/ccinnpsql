import Foundation

public struct ColumnInfo: Sendable, Hashable, Identifiable {
    public var id: Int { number }
    public let number: Int
    public let name: String
    /// `format_type` (`character varying(20)`, `numeric(10,2)`).
    public let type: String
    public let isNullable: Bool
    public let defaultExpression: String?
    /// `a` ALWAYS / `d` BY DEFAULT identity.
    public let identity: String?
    /// Expression of a stored generated column.
    public let generatedExpression: String?
    public let collation: String?
    public let comment: String?
    public let nullFraction: Double?
    public let distinctValues: Double?
    public let averageWidth: Int?
    /// Defined in this table (not only inherited from a parent).
    public let isLocal: Bool

    public init(number: Int, name: String, type: String, isNullable: Bool, defaultExpression: String? = nil, identity: String? = nil,
                generatedExpression: String? = nil, collation: String? = nil, comment: String? = nil, nullFraction: Double? = nil,
                distinctValues: Double? = nil, averageWidth: Int? = nil, isLocal: Bool = true) {
        self.number = number
        self.name = name
        self.type = type
        self.isNullable = isNullable
        self.defaultExpression = defaultExpression
        self.identity = identity
        self.generatedExpression = generatedExpression
        self.collation = collation
        self.comment = comment
        self.nullFraction = nullFraction
        self.distinctValues = distinctValues
        self.averageWidth = averageWidth
        self.isLocal = isLocal
    }

    public var identityDescription: String? {
        switch identity {
        case "a": "GENERATED ALWAYS AS IDENTITY"
        case "d": "GENERATED BY DEFAULT AS IDENTITY"
        default: nil
        }
    }
}

public enum ConstraintKind: String, Sendable, Hashable {
    case primaryKey = "p"
    case foreignKey = "f"
    case unique = "u"
    case check = "c"
    case exclusion = "x"
    case trigger = "t"
    case notNull = "n"

    public var displayName: String {
        switch self {
        case .primaryKey: "Primary key"
        case .foreignKey: "Foreign key"
        case .unique: "Unique"
        case .check: "Check"
        case .exclusion: "Exclusion"
        case .trigger: "Constraint trigger"
        case .notNull: "Not null"
        }
    }
}

