/// Estimated wasted space (from statistics; not an exact measurement).
public struct BloatEstimate: Sendable, Hashable {
    public let actualBytes: Int64
    public let expectedBytes: Int64

    public init(actualBytes: Int64, expectedBytes: Int64) {
        self.actualBytes = max(0, actualBytes)
        self.expectedBytes = max(0, expectedBytes)
    }

    public var wastedBytes: Int64 { max(0, actualBytes - expectedBytes) }
    /// Share of the relation that is estimated to be bloat (0…1).
    public var ratio: Double { actualBytes > 0 ? Double(wastedBytes) / Double(actualBytes) : 0 }
}

/// Size, activity and maintenance facts of one table or materialized view.
public struct TableStatistics: Sendable, Hashable {
    public var heapBytes: Int64?
    public var toastBytes: Int64?
    public var indexBytes: Int64?
    public var totalBytes: Int64?
    public var estimatedRows: Int64?
    public var pages: Int64?
    public var transactionIDAge: Int64?
    public var sequentialScans: Int64?
    public var sequentialTuplesRead: Int64?
    public var indexScans: Int64?
    public var indexTuplesFetched: Int64?
    public var inserted: Int64?
    public var updated: Int64?
    public var deleted: Int64?
    public var hotUpdated: Int64?
    public var liveTuples: Int64?
    public var deadTuples: Int64?
    public var modifiedSinceAnalyze: Int64?
    public var insertedSinceVacuum: Int64?
    public var lastVacuum: Date?
    public var lastAutovacuum: Date?
    public var lastAnalyze: Date?
    public var lastAutoanalyze: Date?
    public var vacuumCount: Int64?
    public var autovacuumCount: Int64?
    public var analyzeCount: Int64?
    public var autoanalyzeCount: Int64?
    public var lastSequentialScan: Date?
    public var heapBlocksRead: Int64?
    public var heapBlocksHit: Int64?
    public var blockSize: Int
    public var fillFactor: Int?
    public var options: [String]
    public var bloat: BloatEstimate?

    public init(blockSize: Int = 8192) {
        self.blockSize = blockSize
        options = []
    }

    /// Dead tuples as a share of all tuples.
    public var deadTupleRatio: Double? {
        guard let live = liveTuples, let dead = deadTuples, live &+ dead > 0 else { return nil }
        return Double(dead) / Double(live &+ dead)
    }

    /// Buffer cache hit ratio of heap reads.
    public var cacheHitRatio: Double? {
        guard let hit = heapBlocksHit, let read = heapBlocksRead, hit &+ read > 0 else { return nil }
        return Double(hit) / Double(hit &+ read)
    }

    public var lastVacuumAny: Date? { [lastVacuum, lastAutovacuum].compactMap { $0 }.max() }
    public var lastAnalyzeAny: Date? { [lastAnalyze, lastAutoanalyze].compactMap { $0 }.max() }
}

