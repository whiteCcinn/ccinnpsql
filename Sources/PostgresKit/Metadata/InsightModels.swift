public struct SequenceInfo: Sendable, Hashable {
    public let dataType: String
    public let startValue: Int64?
    public let increment: Int64?
    public let minValue: Int64?
    public let maxValue: Int64?
    public let cache: Int64?
    public let cycles: Bool
    /// `nil` until `nextval` was called (or without privilege).
    public let lastValue: Int64?
    public let ownedBy: String?

    public init(dataType: String, startValue: Int64?, increment: Int64?, minValue: Int64?, maxValue: Int64?, cache: Int64?, cycles: Bool,
                lastValue: Int64?, ownedBy: String?) {
        self.dataType = dataType
        self.startValue = startValue
        self.increment = increment
        self.minValue = minValue
        self.maxValue = maxValue
        self.cache = cache
        self.cycles = cycles
        self.lastValue = lastValue
        self.ownedBy = ownedBy
    }

    /// Share of the range already used (0…1), in the direction of the increment.
    public var usedFraction: Double? {
        guard let minValue, let maxValue, let increment, maxValue > minValue else { return nil }
        let current = lastValue ?? (increment > 0 ? minValue : maxValue)
        let span = Double(maxValue) - Double(minValue)
        let used = increment > 0 ? Double(current) - Double(minValue) : Double(maxValue) - Double(current)
        guard span > 0, used.isFinite else { return nil }
        return min(1, max(0, used / span))
    }

    public var isNearlyExhausted: Bool { !cycles && (usedFraction ?? 0) >= 0.8 }
}

