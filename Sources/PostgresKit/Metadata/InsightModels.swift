/// Materialized-view facts relevant to refreshing.
public struct MaterializedViewInfo: Sendable, Hashable {
    public let isPopulated: Bool
    /// Has a unique index covering all rows, required by `REFRESH … CONCURRENTLY`.
    public let hasUniqueIndex: Bool
    public let definition: String?

    public init(isPopulated: Bool, hasUniqueIndex: Bool, definition: String?) {
        self.isPopulated = isPopulated
        self.hasUniqueIndex = hasUniqueIndex
        self.definition = definition
    }

    /// Why `CONCURRENTLY` is not possible, if it is not.
    public var concurrentRefreshBlocker: String? {
        if !isPopulated { return "The view has never been populated; a first plain REFRESH is required." }
        if !hasUniqueIndex { return "REFRESH … CONCURRENTLY needs a unique index on the materialized view (without a WHERE clause)." }
        return nil
    }
}

