                constraintName: String? = nil, sizeBytes: Int64? = nil, scans: Int64? = nil, tuplesRead: Int64? = nil,
                tuplesFetched: Int64? = nil, columnNumbers: [Int] = [], estimatedTuples: Double? = nil, pages: Int64? = nil,
